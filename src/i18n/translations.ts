// TranslationKey is open-ended: components can pass either a structured key
// (e.g. "nav.products") or a natural English string as the lookup key.
export type TranslationKey = string;

const deepByLanguage: Partial<Record<Language, Dict>> = {
  "zh-CN": deepZhCN,
  "zh-TW": deepZhTW,
};

export const resolveDict = (region: Region, language: Language): Dict => {
  const langDict = languageDicts[language] ?? en;
  const deep = deepByLanguage[language] ?? {};
  const override = regionOverrides[region]?.[language] ?? {};
  return { ...en, ...deep, ...langDict, ...override };
};
